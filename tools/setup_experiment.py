#!/usr/bin/env python3
"""Install a private CUDA 12.9 / Nsight 2025.2 toolchain and Python plot tools."""

import argparse
import hashlib
import os
from pathlib import Path
import platform
import shlex
import shutil
import subprocess
import sys
import tarfile
import tempfile
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / ".tools"
PREFIX = TOOLS / "cuda12"
BUILD = ROOT / "build-cuda12"
BOOTSTRAP_URL = (
    "https://conda.anaconda.org/conda-forge/linux-64/"
    "micromamba-2.9.0-0.tar.bz2"
)
# SHA256 from conda-forge's HTTPS current_repodata.json; verified against artifact.
BOOTSTRAP_SHA256 = "8761c382127e6363bd9e0a2451aa3ef90d071a79133f736e2f759a3bf13040dd"
PACKAGES = (
    "cuda-version=12.9", "cuda-nvcc=12.9.86", "cuda-cudart-dev=12.9.79",
    "libcublas-dev=12.9.1.4", "cuda-profiler-api=12.9.79", "cuda-cuobjdump=12.9.82",
    "cuda-nvdisasm=12.9.88", "nsight-compute=2025.2.1.3",
    "gcc_linux-64=13", "gxx_linux-64=13", "sysroot_linux-64=2.28",
)
GENERATED = "# Generated by tools/setup_experiment.py; source from bash.\n"


def check_sha256(path, expected):
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    if digest.hexdigest() != expected:
        raise ValueError(f"SHA256 mismatch for {path}; refusing to use this download")


def fetch_bootstrap(destination):
    if destination.exists():
        check_sha256(destination, BOOTSTRAP_SHA256)
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as handle:
        temporary = Path(handle.name)
    try:
        # Default TLS verification remains enabled; no insecure fallback.
        with urllib.request.urlopen(BOOTSTRAP_URL, timeout=120) as response, temporary.open("wb") as output:
            shutil.copyfileobj(response, output)
        check_sha256(temporary, BOOTSTRAP_SHA256)
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)


def extract_micromamba(archive, destination):
    """Extract one regular file only, never archive paths, links or metadata."""
    with tarfile.open(archive, "r:bz2") as handle:
        member = handle.getmember("bin/micromamba")
        if not member.isfile():
            raise ValueError("micromamba archive must contain a regular file")
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(dir=destination.parent, delete=False) as output:
            temporary = Path(output.name)
            try:
                with handle.extractfile(member) as source:
                    shutil.copyfileobj(source, output)
            except BaseException:
                temporary.unlink(missing_ok=True)
                raise
        temporary.chmod(0o755)
        temporary.replace(destination)


def run(command, environment):
    command = [str(part) for part in command]
    print("+ " + shlex.join(command), flush=True)
    subprocess.run(command, check=True, cwd=ROOT, env=environment)


def find_ncu(prefix):
    direct = prefix / "bin" / "ncu"
    if direct.is_file():
        return direct
    candidates = {path.resolve() for path in prefix.rglob("ncu")
                  if path.is_file() and os.access(path, os.X_OK)}
    if len(candidates) != 1:
        raise RuntimeError(f"Expected one Nsight Compute executable under {prefix}, found {len(candidates)}")
    return candidates.pop()


def initialize_prefix(prefix):
    history = prefix / "conda-meta/history"
    if history.is_file():
        return
    if prefix.exists() and any(prefix.iterdir()):
        raise RuntimeError(f"Refusing to overwrite an unmanaged tool directory: {prefix}")
    # Micromamba 2.9 recognizes history as the empty environment marker. Using
    # install on this private prefix avoids create's ~/.conda registration,
    # which fails on cloud hosts with a read-only home. Package installation
    # and validation still run through micromamba normally.
    history.parent.mkdir(parents=True, exist_ok=True)
    history.touch(exist_ok=False)


def write_activation(environment, ncu=None):
    target = TOOLS / "env.sh"
    if target.exists() and not target.read_text().startswith(GENERATED):
        raise RuntimeError(f"Refusing to replace an existing user file: {target}")
    lines = [GENERATED.rstrip(), f"source {shlex.quote(str(ROOT / '.venv/bin/activate'))}"]
    for name in ("PIP_CACHE_DIR", "MPLCONFIGDIR", "MPLBACKEND"):
        lines.append(f"export {name}={shlex.quote(environment[name])}")
    if ncu is not None:
        paths = f"{ROOT / '.venv/bin'}:{PREFIX / 'bin'}:{ncu.parent}"
        lines += [
            f"export PATH={shlex.quote(paths)}:\"$PATH\"",
            f"export CUDACXX={shlex.quote(str(PREFIX / 'bin/nvcc'))}",
            f"export CUDAToolkit_ROOT={shlex.quote(str(PREFIX))}",
            f"export CXX={shlex.quote(str(PREFIX / 'bin/x86_64-conda-linux-gnu-c++'))}",
            'export CUDAHOSTCXX="$CXX"',
            f"export NCU={shlex.quote(str(ncu))}",
            f"export POWERBENCH={shlex.quote(str(BUILD / 'powerbench'))}",
        ]
    else:
        lines.append("# Python-only setup: CUDA/NCU paths are not configured.")
    target.write_text("\n".join(lines) + "\n")
    print(f"Activate in each new shell: source {shlex.quote(str(target))}", flush=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python-only", action="store_true",
                        help="install Python/plot/CMake tools without CUDA or Nsight")
    parser.add_argument("--build", action="store_true",
                        help="also compile powerbench for V100/A100/H100 (70;80;90)")
    parser.add_argument("--jobs", type=int, default=2, help="parallel build jobs (default: 2)")
    args = parser.parse_args(argv)
    if args.jobs < 1:
        parser.error("--jobs must be positive")
    if args.python_only and args.build:
        parser.error("--build requires the CUDA toolchain; omit --python-only")
    if sys.version_info < (3, 10):
        parser.error("Python >=3.10 is required")
    if not args.python_only and (sys.platform != "linux" or platform.machine() != "x86_64"):
        parser.error("CUDA installation supports Linux x86_64; use --python-only elsewhere")
    environment = os.environ.copy()
    environment.update(
        PIP_CACHE_DIR=str(TOOLS / "cache/pip"),
        MPLCONFIGDIR=str(TOOLS / "cache/matplotlib"),
        MPLBACKEND="Agg",
        XDG_CACHE_HOME=str(TOOLS / "cache"),
        MAMBA_ROOT_PREFIX=str(TOOLS / "mamba"),
        CONDA_PKGS_DIRS=str(TOOLS / "mamba/pkgs"),
        MAMBA_USE_SHARDED_REPODATA="false",
    )
    for key in ("PIP_CACHE_DIR", "MPLCONFIGDIR", "XDG_CACHE_HOME"):
        Path(environment[key]).mkdir(parents=True, exist_ok=True)
    # Honor the cloud's injected CA trust bundle, without disabling verification.
    if environment.get("SSL_CERT_FILE"):
        environment["MAMBA_SSL_VERIFY"] = environment["SSL_CERT_FILE"]
    python = ROOT / ".venv/bin/python"
    if not python.is_file():
        run([sys.executable, "-m", "venv", ROOT / ".venv"], environment)
    run([python, "-m", "pip", "install", "--disable-pip-version-check",
         "-e", f"{ROOT}[plots]", "cmake>=3.22,<4", "ninja>=1.11"], environment)
    run([python, "-m", "pip", "check"], environment)
    if args.python_only:
        write_activation(environment)
        return 0

    archive = TOOLS / "cache/micromamba-2.9.0-0.tar.bz2"
    fetch_bootstrap(archive)
    mamba = TOOLS / "bin/micromamba"
    extract_micromamba(archive, mamba)
    initialize_prefix(PREFIX)
    base = [mamba, "--no-rc", "--root-prefix", TOOLS / "mamba"]
    run(base + ["install", "--yes", "--prefix", PREFIX,
                "--override-channels", "--strict-channel-priority",
                "-c", "nvidia", "-c", "conda-forge", *PACKAGES], environment)
    ncu = find_ncu(PREFIX)
    compiler = PREFIX / "bin/x86_64-conda-linux-gnu-c++"
    if not compiler.is_file():
        raise RuntimeError(f"Missing installed host compiler: {compiler}")
    for command in ([PREFIX / "bin/nvcc", "--version"],
                    [PREFIX / "bin/cuobjdump", "--version"],
                    [PREFIX / "bin/nvdisasm", "--version"], [ncu, "--version"]):
        run(command, environment)
    write_activation(environment, ncu)
    if args.build:
        cmake = ROOT / ".venv/bin/cmake"
        activated = base + ["run", "--prefix", PREFIX]
        run(activated + [cmake, "-S", ROOT, "-B", BUILD, "-G", "Ninja",
                         f"-DCMAKE_MAKE_PROGRAM={ROOT / '.venv/bin/ninja'}",
                         "-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_CUDA_ARCHITECTURES=70;80;90",
                         f"-DCMAKE_CUDA_COMPILER={PREFIX / 'bin/nvcc'}",
                         f"-DCUDAToolkit_ROOT={PREFIX}",
                         f"-DCMAKE_CXX_COMPILER={compiler}",
                         f"-DCMAKE_CUDA_HOST_COMPILER={compiler}"], environment)
        run(activated + [cmake, "--build", BUILD, "--parallel", args.jobs], environment)
        run([BUILD / "powerbench", "--help"], environment)
    print("Tool installation verified. GPU execution, driver access and NCU counter permissions require a GPU host.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, RuntimeError, subprocess.CalledProcessError, tarfile.TarError) as exc:
        print(f"setup_experiment: {exc}", file=sys.stderr)
        raise SystemExit(1)
